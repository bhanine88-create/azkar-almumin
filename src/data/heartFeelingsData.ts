const CUSTOM_DUAS_STORAGE_KEY = 'azkar_custom_heart_duas';

export function getCustomHeartDuas(): CustomHeartDua[] {
  try {
    const raw = localStorage.getItem(CUSTOM_DUAS_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch (e) {
    console.error('Failed to load custom heart duas:', e);
    return [];
  }
}

export function saveCustomHeartDua(feelingId: string, title: string, text: string, source?: string): CustomHeartDua {
  const list = getCustomHeartDuas();
  const newDua: CustomHeartDua = {
    id: `custom-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`,
    feelingId,
    title: title.trim() || 'دعاء مخصص',
    text: text.trim(),
    source: source?.trim() || 'دعاء شخصي مضاف',
    createdAt: Date.now()
  };
  const updated = [newDua, ...list];
  try {
    localStorage.setItem(CUSTOM_DUAS_STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Failed to save custom heart dua:', e);
  }
  return newDua;
}

export function deleteCustomHeartDua(id: string): boolean {
  const list = getCustomHeartDuas();
  const updated = list.filter(item => item.id !== id);
  try {
    localStorage.setItem(CUSTOM_DUAS_STORAGE_KEY, JSON.stringify(updated));
    return true;
  } catch (e) {
    console.error('Failed to delete custom heart dua:', e);
    return false;
  }
}
