export function getLocalizedVocab(vocabId: string, lang: string): { meaning: string; impact: string } | null {
  const item = QURAN_VOCABULARY_TRANSLATIONS[vocabId];
  if (!item) return null;

  let meaning = item.enMeaning;
  let impact = item.enImpact;

  if (lang === 'fr' && item.frMeaning && item.frImpact) {
    meaning = item.frMeaning;
    impact = item.frImpact;
  } else if (lang === 'ur' && item.urMeaning && item.urImpact) {
    meaning = item.urMeaning;
    impact = item.urImpact;
  } else if ((lang === 'id' || lang === 'ms') && item.idMeaning && item.idImpact) {
    meaning = item.idMeaning;
    impact = item.idImpact;
  } else if (lang === 'tr' && item.trMeaning && item.trImpact) {
    meaning = item.trMeaning;
    impact = item.trImpact;
  }

  return { meaning, impact };
}
