#!/usr/bin/env node
/**
 * Rebuilds the Android adaptive launcher icon after `@capacitor/assets`.
 *
 * What that tool leaves behind, and why it is wrong
 * -------------------------------------------------
 * It writes the two adaptive layers at *launcher* pixel sizes (48/72/96/144/192)
 * and then insets both by 16.7% in the XML. An adaptive layer is a 108dp canvas,
 * not a 48dp one, so that produces two defects:
 *
 *   1. The background stops at the central 66.6% of the canvas — exactly the
 *      area the mask keeps. It has no bleed, so a launcher that reveals a little
 *      more than 72dp, or shifts the layers for parallax, exposes transparent
 *      corners around the icon.
 *   2. Our foreground already includes the launcher-mask padding, so the
 *      extra inset shrinks it twice: it lands at ~50% of the visible icon and
 *      looks small and off-brand next to the legacy icon.
 *
 * This rewrites both layers the way the platform expects:
 *   - foreground rasterised on a true 108dp canvas per density
 *   - background as a solid colour drawable, which fills the canvas edge to edge
 *     at any size and can never leave a gap
 *   - a monochrome layer so Android 13+ themed icons work
 *   - no insets in the XML
 */
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ICONS_ONLY = process.argv.includes('--icons-only');
const RES = path.join(ROOT, 'android', 'app', 'src', 'main', 'res');
const ASSETS = path.join(ROOT, 'assets');

const BRAND_GREEN = '#083927';

/** An adaptive layer is 108dp square; these are 108dp at each density. */
const ADAPTIVE_DENSITIES = [
  ['ldpi', 81],
  ['mdpi', 108],
  ['hdpi', 162],
  ['xhdpi', 216],
  ['xxhdpi', 324],
  ['xxxhdpi', 432],
];

/** Notification small icons are 24dp square. */
const NOTIFY_DENSITIES = [
  ['ldpi', 18],
  ['mdpi', 24],
  ['hdpi', 36],
  ['xhdpi', 48],
  ['xxhdpi', 72],
  ['xxxhdpi', 96],
];

function magick(args) {
  execFileSync('magick', args, { stdio: ['ignore', 'pipe', 'pipe'] });
}

if (!existsSync(RES)) {
  console.error('No android/ project yet. Run `npx cap add android` first.');
  process.exit(1);
}

const foregroundSrc = path.join(ASSETS, 'icon-foreground.png');
const monochromeSrc = path.join(ASSETS, 'icon-monochrome.png');
for (const src of [foregroundSrc, monochromeSrc]) {
  if (!existsSync(src)) {
    console.error(`Missing ${path.relative(ROOT, src)} — run scripts/generate-brand-assets.mjs first.`);
    process.exit(1);
  }
}

console.log('· adaptive foreground + monochrome at true 108dp sizes');
for (const [density, size] of ADAPTIVE_DENSITIES) {
  const dir = path.join(RES, `mipmap-${density}`);
  mkdirSync(dir, { recursive: true });

  magick([foregroundSrc, '-filter', 'Lanczos', '-resize', `${size}x${size}`, '-strip', path.join(dir, 'ic_launcher_foreground.png')]);
  magick([monochromeSrc, '-filter', 'Lanczos', '-resize', `${size}x${size}`, '-strip', path.join(dir, 'ic_launcher_monochrome.png')]);

  // The background is a colour now, so the raster it generated is dead weight.
  const staleBackground = path.join(dir, 'ic_launcher_background.png');
  if (existsSync(staleBackground)) rmSync(staleBackground);
}

if (!ICONS_ONLY) console.log('· notification small icons (silhouette, tinted by the system)');
for (const [density, size] of ICONS_ONLY ? [] : NOTIFY_DENSITIES) {
  const dir = path.join(RES, `drawable-${density}`);
  mkdirSync(dir, { recursive: true });
  const src = path.join(ASSETS, 'notification', `drawable-${density}`, 'ic_stat_notify.png');
  if (!existsSync(src)) continue;
  magick([src, '-resize', `${size}x${size}`, '-strip', path.join(dir, 'ic_stat_notify.png')]);
}

console.log('· adaptive-icon XML without insets');
const adaptiveXml = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by scripts/fix-adaptive-icons.mjs — do not hand-edit.

  No <inset> on either layer: the foreground raster already includes padding
  for launcher masks, and the background is a colour so it always fills
  the full 108dp canvas no matter how a launcher masks or shifts it.
-->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
`;

const anydpi = path.join(RES, 'mipmap-anydpi-v26');
mkdirSync(anydpi, { recursive: true });
writeFileSync(path.join(anydpi, 'ic_launcher.xml'), adaptiveXml);
writeFileSync(path.join(anydpi, 'ic_launcher_round.xml'), adaptiveXml);

console.log('· ic_launcher_background colour');
writeFileSync(
  path.join(RES, 'values', 'ic_launcher_background.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/fix-adaptive-icons.mjs — the adaptive icon's base layer. -->
<resources>
    <color name="ic_launcher_background">${BRAND_GREEN}</color>
</resources>
`
);

if (!ICONS_ONLY) console.log('· portrait splash in the night fallback bucket');
/**
 * `@capacitor/assets` puts the LANDSCAPE dark splash into `drawable-night/`.
 *
 * That bucket is the orientation- and density-agnostic fallback, so any device
 * that resolves to it in dark mode gets a 4:3 landscape image stretched down a
 * portrait window — the wordmark squashed and off-centre on the very first
 * screen of the app. `drawable/` correctly gets the portrait splash for light
 * mode; this makes the dark fallback match it.
 */
const nightSplashFallback = path.join(RES, 'drawable-night', 'splash.png');
const nightSplashPortrait = path.join(RES, 'drawable-port-night-mdpi', 'splash.png');
if (!ICONS_ONLY && existsSync(nightSplashPortrait)) {
  copyFileSync(nightSplashPortrait, nightSplashFallback);
} else if (!ICONS_ONLY) {
  console.warn('  no drawable-port-night-mdpi/splash.png — left the night fallback alone');
}

console.log('· legacy launcher icons, full-bleed');
/**
 * `ic_launcher.png` / `ic_launcher_round.png` — the pre-adaptive icons.
 *
 * These matter more than the API-26+ layers suggest: LDPlayer's launcher and
 * the stock launchers on a number of OEM skins ignore the adaptive XML and draw
 * these PNGs directly. As `@capacitor/assets` writes them, the square one is
 * inset 4% per side with a transparent border, on top of the wordmark already
 * sitting at 72% of the source. Next to Telegram or WhatsApp, which fill their
 * tile edge to edge, ours read as a small logo in a small box with a margin —
 * exactly the client's words.
 *
 * Rebuilt here: the square icon is the Play/brand source (full green, wordmark
 * at LEGACY_SCALE) resized to each density and given a 20% corner radius, no
 * inset; the round icon composes the wordmark at ROUND_SCALE directly onto
 * green and masks it to a full circle.
 */
const LEGACY_DENSITIES = [
  ['ldpi', 36],
  ['mdpi', 48],
  ['hdpi', 72],
  ['xhdpi', 96],
  ['xxhdpi', 144],
  ['xxxhdpi', 192],
];
// The unmasked calligraphy stays well inside the circle, with a visible margin.
// Keep this separate from the 68% square tile, whose corners are not circular.
const ROUND_SCALE = 0.64;
const legacySrc = path.join(ASSETS, 'icon.png');
const wordmarkSrc = path.join(ASSETS, '.wordmark-trimmed.png');
if (existsSync(legacySrc) && existsSync(wordmarkSrc)) {
  for (const [density, size] of LEGACY_DENSITIES) {
    const dir = path.join(RES, `mipmap-${density}`);
    const radius = Math.round(size * 0.2);
    // Square: resize, then keep only the rounded rectangle.
    magick([
      legacySrc, '-filter', 'Lanczos', '-resize', `${size}x${size}`,
      '(', '-size', `${size}x${size}`, 'xc:none', '-fill', 'white',
      '-draw', `roundrectangle 0,0 ${size - 1},${size - 1} ${radius},${radius}`, ')',
      '-alpha', 'off', '-compose', 'CopyOpacity', '-composite', '-strip',
      path.join(dir, 'ic_launcher.png'),
    ]);
    // Round: wordmark on green, then keep only the circle.
    const art = Math.round(size * ROUND_SCALE);
    magick([
      '-size', `${size}x${size}`, `xc:${BRAND_GREEN}`,
      '(', wordmarkSrc, '-filter', 'Lanczos', '-resize', `${art}x${art}`, ')',
      '-gravity', 'center', '-composite',
      '(', '-size', `${size}x${size}`, 'xc:none', '-fill', 'white',
      '-draw', `circle ${size / 2},${size / 2} ${size / 2},0`, ')',
      '-alpha', 'off', '-compose', 'CopyOpacity', '-composite', '-strip',
      path.join(dir, 'ic_launcher_round.png'),
    ]);
  }
} else {
  console.warn('  missing assets/icon.png or assets/.wordmark-trimmed.png — legacy icons left as generated');
}

if (!ICONS_ONLY) console.log('· window-background wordmark at 216dp');
/**
 * The density-specific window_wordmark.png is sized to 216dp for
 * drawable/window_splash.xml (the activity's window background).
 *
 * 216dp is the width the HTML boot splash in index.html gives the same
 * wordmark (`min(54vw, 216px)` CSS px), so the frame the window background
 * covers — the activity's first draw, before the WebView has presented — is
 * pixel-for-pixel what the HTML splash then draws over it.
 */
const WINDOW_WORDMARK_DP = 216;
const DENSITY_SCALE = [
  ['ldpi', 0.75],
  ['mdpi', 1],
  ['hdpi', 1.5],
  ['xhdpi', 2],
  ['xxhdpi', 3],
  ['xxxhdpi', 4],
];
if (!ICONS_ONLY && existsSync(wordmarkSrc)) {
  for (const [density, scale] of DENSITY_SCALE) {
    const dir = path.join(RES, `drawable-${density}`);
    mkdirSync(dir, { recursive: true });
    const width = Math.round(WINDOW_WORDMARK_DP * scale);
    // 32 colours: the wordmark is two flat colours plus anti-aliasing, and at
    // full depth these six PNGs added 0.9 MB to the APK for no visible gain.
    magick([wordmarkSrc, '-filter', 'Lanczos', '-resize', `${width}x`, '-strip', '-colors', '32', '-define', 'png:compression-level=9', path.join(dir, 'window_wordmark.png')]);
  }
}

/**
 * Android 12+ draws a system splash before our activity or WebView exists.
 * Give that splash a transparent 288dp square icon, with the wordmark centered
 * within its 192dp circular visible region. A launcher adaptive icon would
 * show its lighter green tile against the darker splash background.
 */
if (!ICONS_ONLY) console.log('· Android system-splash wordmark');
const LAUNCH_ICON_DP = 288;
// 136dp square fits completely inside the platform's 192dp circular mask.
const LAUNCH_ART_DP = 136;
if (!ICONS_ONLY && existsSync(wordmarkSrc)) {
  for (const [density, scale] of DENSITY_SCALE) {
    const dir = path.join(RES, `drawable-${density}`);
    mkdirSync(dir, { recursive: true });
    const size = Math.round(LAUNCH_ICON_DP * scale);
    const art = Math.round(LAUNCH_ART_DP * scale);
    magick([
      '-size', `${size}x${size}`, 'xc:none',
      '(', wordmarkSrc, '-filter', 'Lanczos', '-resize', `${art}x${art}`, ')',
      '-gravity', 'center', '-composite', '-strip', '-colors', '64',
      '-define', 'png:compression-level=9', path.join(dir, 'launch_wordmark.png'),
    ]);
  }
}

console.log('\nAdaptive icon rebuilt.');
